#pragma once

#include <cstdint>
#include <string>

#include "artifact.hpp"

struct llama_model;

namespace ame::backend {

struct MoeStreamStats {
  std::uint64_t contract_routed{0};
  std::uint64_t contract_shared{0};
  std::uint64_t materialize_calls{0};
  std::uint64_t tensor_switches{0};
  std::uint64_t reads{0};
  std::uint64_t read_bytes{0};
  double read_seconds{0.0};
  std::uint64_t hits{0};
  std::uint64_t misses{0};
  std::uint64_t evictions{0};
  std::uint64_t max_union{0};
  std::uint64_t slots{0};
  std::uint64_t arena_bytes{0};
  std::uint32_t manifest_version{0};
  bool manifest_identity_checked{false};
  std::string manifest_layout_hash;
  std::string declared_artifact_sha256;
  std::string verified_artifact_sha256;
  double artifact_hash_seconds{0.0};
  bool artifact_verified{false};
  bool failed{false};
  bool cancelled{false};
  std::string error;
};

// Install the ggml MUL_MAT_ID materializer. The manifest is generated by
// tools/gguf_index.py. Arenas are allocated lazily per expert payload size and are
// bounded by arena_limit_bytes. One active generation is the MVP contract.
// Verified release path: the artifact FD and GGUF tensor table are authoritative.
bool install_moe_stream(const Artifact& artifact, const std::string& manifest_path,
                        std::uint32_t slots, std::uint64_t arena_limit_bytes);

// Diagnostic path used only by synthetic gates. It refuses unless
// AME_ALLOW_UNVERIFIED_ARTIFACT=1 is set; it never grants verified status.
bool install_moe_stream(const std::string& model_path, const std::string& manifest_path,
                        std::uint32_t slots, std::uint64_t arena_limit_bytes);
void uninstall_moe_stream();

// Release pinned expert leases without destroying the cache or model. Safe after
// all backend workers for a request have drained.
void release_moe_stream_leases();

// Start one request under exclusive admission. Releases leases, clears the request
// cancellation, the failed/cancelled/error outcome, and the backend's process-global
// error latch so the previous request's terminal state cannot abort this one. Call it
// only when no graph is computing and the previous request's context has been
// destroyed. Capture the terminal outcome (moe_stream_stats) before calling.
void begin_moe_stream_request();

// Bind the loaded backend's source-derived routed/shared expert consumers to the
// verified manifest. Must be called after model load and before generation.
bool bind_model_contract(const llama_model* model, std::string& error);

// Admit a prefill token unit from the bound source-derived consumers. Returns false
// with a precise reason when any pool or lease bound cannot be satisfied.
bool plan_model_prefill(std::uint32_t batch_size, std::uint32_t lease_limit,
                        std::uint32_t& unit_tokens, std::uint32_t& expert_count,
                        std::uint32_t& max_selected, std::string& error);
// Request cancellation of the active materializer. Reads observe it between chunks
// and expert slots; the inference owner still drains the current backend call.
void request_moe_stream_cancel();
[[nodiscard]] bool moe_stream_failed();
[[nodiscard]] bool moe_stream_cancelled();
[[nodiscard]] std::string moe_stream_error();
[[nodiscard]] MoeStreamStats moe_stream_stats();

}  // namespace ame::backend