// How expert bytes are cached. Legacy keeps the original design: one pool per expert
// byte size, keyed by (tensor, expert), shared by every routed tensor, evicted least
// recently used. Layered keys by (layer, expert): a slot holds the gate, up and down slices
// of one expert, and every layer has its own pool, so a routing decision is one reservation
// and the 40-layer cycle cannot flush the whole cache. Layered refuses models whose routed
// tensors are not separate gate, up and down tensors with equal expert counts.
enum class CacheLayout { Legacy, Layered };
enum class Eviction { Lru, Lfu };

struct StreamOptions {
  CacheLayout layout{CacheLayout::Legacy};
  Eviction eviction{Eviction::Lru};   // layered only
  std::uint32_t lfu_halve_every{32};  // layered, LFU only
  // Layered: slots per layer. Zero derives it from the arena allowance, the largest pool
  // that fits arena plus bookkeeping.
  std::uint32_t layer_slots{0};
  bool fadvise_random{false};    // layered: no readahead on the read descriptor
  bool fadvise_dontneed{false};  // layered: drop each extent's page-cache pages
  // Reader threads for the misses of one acquire, 1 to 4 (both layouts). One reads on the
  // calling thread. reader_cpus restricts each reader thread to those CPUs (best effort).
  unsigned readers{1};
  std::vector<int> reader_cpus{};
  // Layered only. Start a layer's reads when the router's top-k result is known (see
  // moe_eval_callback) so the operator only waits for its own role's slices. Needs the callback
  // to be installed in the llama context (cb_eval); without it nothing changes.
  bool overlap{false};
};

// Install the ggml MUL_MAT_ID materializer. The manifest is generated by
// tools/gguf_index.py. Arenas are allocated lazily per expert payload size and are
// bounded by arena_limit_bytes. One active generation is the MVP contract.
// Verified release path: the artifact FD and GGUF tensor table are authoritative.
bool install_moe_stream(const Artifact& artifact, const std::string& manifest_path,
                        std::uint32_t slots, std::uint64_t arena_limit_bytes);
bool install_moe_stream(const Artifact& artifact, const std::string& manifest_path,
                        std::uint32_t slots, std::uint64_t arena_limit_bytes,
                        const StreamOptions& options);

// Diagnostic path used only by synthetic gates. It refuses unless
// AME_ALLOW_UNVERIFIED_ARTIFACT=1 is set; it never grants verified status.
bool install_moe_stream(const std::string& model_path, const std::string& manifest_path,
                        std::uint32_t slots, std::uint64_t arena_limit_bytes);
bool install_moe_stream(const std::string& model_path, const std::string& manifest_path,
                        std::uint32_t slots, std::uint64_t arena_limit_bytes,
                        const StreamOptions& options);
void uninstall_moe_stream();

// Release pinned expert leases without destroying the cache or model. Safe after
// all backend workers for a request have drained.
void release_moe_stream_leases();

// Start one request under exclusive admission. Releases leases, clears the request
// cancellation, the failed/cancelled/error outcome, and the backend's process-global
// error latch so the previous request's terminal state cannot abort this one. Call it
// only when no graph is computing and the previous request's context has been
// destroyed. Capture the terminal outcome (moe_stream_stats) before calling. It also
// re-reads the injected-fault environment, so a test can switch faults between requests.
void begin_moe_stream_request();

// Label the next graph in the routing trace: phase is "prefill" or "decode", and
// ubatch_tokens is the number of tokens in the ubatch. Call it once before each
// llama_decode. Without labels a trace row has phase "unknown" and ubatch 0.
void label_moe_graph(const char* phase, std::uint32_t ubatch_tokens);

// Bind the loaded backend's source-derived routed/shared expert consumers to the
// verified manifest. Must be called after model load and before generation.
bool bind_model_contract(const llama_model* model, std::string& error);

// Admit a prefill token unit from the bound source-derived consumers. Returns false
// with a precise reason when any pool or lease bound cannot be satisfied.
bool plan_model_prefill(std::uint32_t batch_size, std::uint32_t lease_limit,
                        std::uint32_t& unit_tokens, std::uint32_t& expert_count,
                        std::uint32_t& max_selected, std::string& error);
// Scheduler eval callback (llama_context_params.cb_eval) for the top-k overlap. It asks for the
// router's `ffn_moe_topk-<layer>` tensors and, when one is ready, starts that layer's reads in
// the background. Pass it with a null user data pointer. It never changes which experts are
// computed: the operator still stages exactly the experts the router selected.
bool moe_eval_callback(struct ggml_tensor* tensor, bool ask, void* user_data);

// Request cancellation of the active materializer. Reads observe it between chunks
// and expert slots; the inference owner still drains the current backend call.
void request_moe_stream_cancel();
[[nodiscard]] bool moe_stream_failed();
[[nodiscard]] bool moe_stream_cancelled();
[[nodiscard]] std::string moe_stream_error();
[[nodiscard]] MoeStreamStats moe_stream_stats();

